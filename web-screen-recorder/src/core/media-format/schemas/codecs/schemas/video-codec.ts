import { z } from "zod";

/**
 * `MediaRecorder API`에서 사용할 수 있는 비디오 코덱들을 정의합니다.
 * 각 코덱은 다음과 같은 특징을 가집니다:
 *
 * - vp8: Google이 개발한 오픈 소스 비디오 코덱. WebRTC 및 실시간 통신에 최적화되어 있으며,
 *        중간 품질 대비 높은 압축 효율을 제공합니다. 로열티가 필요하지 않습니다.
 *
 * - vp9: Google이 개발한 차세대 비디오 코덱. VP8보다 더 높은 압축률을 지원하며,
 *        4K UHD 영상 스트리밍에 널리 사용됩니다. HEVC(H.265)와 경쟁하는 포맷입니다.
 *
 * - h264: ITU-T과 MPEG가 공동 개발한 산업 표준 코덱. 거의 모든 기기와 플랫폼에서 호환되며,
 *        MP4/MKV 컨테이너에서 널리 사용됩니다. 상업적 사용 시 MPEG LA의 라이선스가 필요할 수 있습니다.
 *
 * 이 스키마는 Zod를 사용하여 타입 안전성을 보장하며,
 * `VideoCodec` 타입은 이 스키마를 기반으로 자동 생성됩니다.
 */
export const VideoCodecSchema = z.enum(["vp8", "vp9", "h264"]);
